import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(path.dirname(new URL(import.meta.url).pathname),'../..');
const main=fs.readFileSync(path.join(root,'frontend/main.js'),'utf8');
const composer=fs.readFileSync(path.join(root,'frontend/composer.js'),'utf8');
const native=fs.readFileSync(path.join(root,'frontend/native_window.js'),'utf8');
const nativeWindows=fs.readFileSync(path.join(root,'frontend/native_windows.js'),'utf8');
const rust=fs.readFileSync(path.join(root,'src-tauri/src/lib.rs'),'utf8');
const css=fs.readFileSync(path.join(root,'frontend/styles.css'),'utf8');
const caps=fs.readFileSync(path.join(root,'src-tauri/capabilities/default.json'),'utf8');
for(const m of ['openNativeComposer(ctx,seed)','openNativeReader(id','previewLocalDraft(item.local_draft_id)','handleLocalDraftClick','openMessage(id)',"['ArrowDown','ArrowUp','Home','End','PageUp','PageDown']","$('#rowsViewport')?.focus({preventScroll:true})"])assert.ok(main.includes(m),`main sem ${m}`);
for(const m of ['choiceDialog','Salvar em Rascunhos','Descartar','options.nativeWindow','onNativeClose'])assert.ok(composer.includes(m),`composer sem ${m}`);
for(const m of ['onCloseRequested','initComposer','initReader','openComposerSurface','nativeReaderSurface'])assert.ok(native.includes(m),`native_window sem ${m}`);
for(const m of ['open_mail_window','save_local_draft','draftPayloadFromSeed'])assert.ok(nativeWindows.includes(m),`native_windows sem ${m}`);
assert.match(rust,/fn\s+open_mail_window\b/);
assert.ok(rust.includes('WebviewWindowBuilder::new'));
assert.ok(rust.includes('window.label() == "main"'),'tray close deve valer apenas para main');
assert.ok(caps.includes('composer-*')&&caps.includes('reader-*'),'capabilities sem janelas dinâmicas');
assert.ok(css.includes('body.nativeComposerWindow')&&css.includes('.singleLine{flex-wrap:wrap;overflow-x:visible}'),'CSS nativo/sem barra horizontal ausente');
assert.equal(main.includes("r.onclick=e=>item?.local_draft?openLocalDraft"),false,'clique simples em draft não pode abrir composer');
console.log('MULTI-WINDOW / READER / DRAFT UX CONTRACT: PASS');
